/**
 * Member references found in the bytecode of the classes in the analyzed packages.
 *
 * TASTy is pickled before the `inlining` phase, so the implicit searches that happen while expanding non-`transparent`
 * inline methods -- `summonFrom`, `summonAll`, `summonInline` inside an inline method, `Expr.summon` in a macro --
 * leave no trace in TASTy. The bytecode is generated after inlining, so it does contain calls to the `given`s that
 * were summoned. See https://github.com/scala/scala3/issues/22701
 *
 * @param references member names to the internal names of the classes they're referenced on, each with the class and
 *                   method the reference is made from
 * @param supertypes internal class names to the internal names of their direct superclass and interfaces
 * @param outers internal names of anonymous and local classes to the class and method they're defined in
 */
case class BytecodeReferences(
  references: Map[String, Set[(String, Bytecode.Caller)]],
  supertypes: Map[String, List[String]],
  outers: Map[String, (String, Option[String])],
) {
  private val ancestorsCache = Memo[String, Set[String]]()

  // The JVM names the static type of the receiver as the owner of a member reference, not the class that declares it,
  // so a reference to an inherited member can be on any subclass of the declaring class
  private def ancestors(cls: String): Set[String] =
    ancestorsCache(cls) {
      @annotation.tailrec
      def go(acc: Set[String], todo: List[String]): Set[String] =
        todo match {
          case Nil => acc
          case c :: rest if acc.contains(c) => go(acc, rest)
          case c :: rest => go(acc + c, supertypes.getOrElse(c, Nil) ::: rest)
        }

      go(Set.empty, List(cls))
    }

  /** The classes and methods that reference `sym`; empty if nothing does */
  def callers(sym: Symbol): Set[Bytecode.Caller] =
    Bytecode.memberKey(sym).toSet.flatMap { (owner, name) =>
      // A private member can only be referenced on its own class: a subclass's same-named private member, like the
      // `evidence$1` of its own context bound, is a different member
      val isPrivate = sym match {
        case t: TermSymbol => t.isPrivate
        case _ => false
      }
      // A private member that's accessed from another class, e.g. from an anonymous class generated by derivation, is
      // compiled with an expanded name, e.g. `bl$Foo$$$bar` for `bar` in `object Foo` in package `bl`
      List(name, owner.replace('/', '$') ++ "$$" ++ name).flatMap(n =>
        references.getOrElse(n, Set.empty).collect {
          case (o, caller) if (if (isPrivate) o == owner else ancestors(o).contains(owner)) => caller
        }
      )
    }

  /**
   * The classes and methods that reference an `object`; empty if nothing does. One nested in a class is reached through
   * its accessor, and any other through the static `MODULE$` field holding its instance.
   */
  def moduleCallers(cls: ClassSymbol)(using ctx: Context): Set[Bytecode.Caller] =
    Bytecode.internalClassName(cls).toSet.flatMap(moduleReads.getOrElse(_, Set.empty)) ++
      cls.moduleValue.toSet.flatMap(callers)

  // Reads of `MODULE$` by the class they read it from, so finding an object's isn't a search through all of them
  private lazy val moduleReads: Map[String, Set[Bytecode.Caller]] =
    references.getOrElse(Bytecode.moduleField, Set.empty).groupMap(_._1)(_._2)
}

object Bytecode {
  // The internal name of a class and the name of a method in it
  type Caller = (String, String)

  // The static field holding an `object`'s instance
  private[unused] val moduleField = "MODULE$"

  private def encode(name: String): String = NameTransformer.encode(name)

  /**
   * The JVM internal name of a class, e.g. `bl/unused/Foo$` for `object Foo` in package `bl.unused`
   *
   * Returns `None` for local classes, whose names get a compiler-generated numeric suffix.
   */
  def internalClassName(cls: ClassSymbol): Option[String] =
    Option(cls.owner).flatMap {
      case p: PackageSymbol =>
        Some((p.fullName.path.map(n => encode(n.toString)) :+ encode(cls.name.toString)).mkString("/"))
      // A nested class is named `Outer$Inner`, whether `Outer` is a class (`Outer`) or an object (`Outer$`)
      case o: ClassSymbol => internalClassName(o).map(_.stripSuffix("$") ++ "$" ++ encode(cls.name.toString))
      case _ => None
    }

  /** The internal name of the class that declares a member, along with the member's JVM name */
  def memberKey(sym: Symbol): Option[(String, String)] =
    Option(sym.owner).collect { case c: ClassSymbol => c }.flatMap(internalClassName).map((_, encode(sym.name.toString)))

  private case class Reference(owner: String, name: String)

  /**
   * Whether a reference is part of the machinery the compiler generates for the member itself, rather than a use of it.
   *
   * Given a member `foo` in `object Foo`, this covers:
   *
   *   1. The static forwarder `Foo.foo` in the companion/mirror class, which calls `Foo$.foo`
   *   2. Bridge methods named `foo` in `Foo$`, which call `Foo$.foo`
   *   3. Methods like `foo$lzyINIT1` that initialize a `lazy val`, and the `foo` getter that reads the `foo` field
   *   4. For a member of a trait, the static `foo$` implementation method, which calls `foo`
   *
   * Direct recursion is also skipped, but it's visible in TASTy already. So is an `object` reading its own instance,
   * which it and the static forwarders in its companion class do. A local method lifted out of another member is named
   * like `foo$1`, so a suffix starting with a digit is a different method, which can use `foo`.
   */
  private def isSelfReference(cls: String, method: String, isStatic: Boolean, ref: Reference): Boolean =
    (cls == ref.owner && (method == ref.name || isGeneratedFor(ref.name, method) || ref.name == moduleField)) ||
      (cls ++ "$" == ref.owner && isStatic && (method == ref.name || ref.name == moduleField))

  private def isGeneratedFor(member: String, method: String): Boolean =
    method.startsWith(member ++ "$") && !method.lift(member.length + 1).exists(_.isDigit)

  /**
   * A class's supertypes, the references in its bytecode to members of classes in the analyzed packages along with the
   * methods they're made from, and the class and method it's defined in, if it's an anonymous or local class
   */
  private case class ClassInfo(
    name: String,
    supertypes: List[String],
    references: Set[(Reference, String)],
    outer: Option[(String, Option[String])],
  )

  private def readClass(bytes: Array[Byte], packagePrefixes: List[String]): ClassInfo = {
    var cls = ""
    var supertypes = List.empty[String]
    var outer = Option.empty[(String, Option[String])]
    val references = mutable.Set.empty[(Reference, String)]

    def methodVisitor(method: String, isStatic: Boolean): MethodVisitor = {
      def add(ref: Reference): Unit =
        if (packagePrefixes.exists(ref.owner.startsWith) && !isSelfReference(cls, method, isStatic, ref))
          references += ((ref, method))

      new MethodVisitor(Opcodes.ASM9) {
        override def visitMethodInsn(opcode: Int, owner: String, name: String, descriptor: String, isInterface: Boolean): Unit =
          add(Reference(owner, name))

        // Only reads count as uses -- writes are field initialization
        override def visitFieldInsn(opcode: Int, owner: String, name: String, descriptor: String): Unit =
          if (opcode == Opcodes.GETFIELD || opcode == Opcodes.GETSTATIC) add(Reference(owner, name))

        override def visitInvokeDynamicInsn(name: String, descriptor: String, bsm: Handle, bsmArgs: Object*): Unit =
          bsmArgs.foreach {
            case h: Handle => add(Reference(h.getOwner, h.getName))
            case _ => ()
          }
      }
    }

    new ClassReader(bytes).accept(
      new ClassVisitor(Opcodes.ASM9) {
        override def visit(
          version: Int,
          access: Int,
          name: String,
          signature: String,
          superName: String,
          interfaces: Array[String],
        ): Unit = {
          cls = name
          supertypes = Option(superName).toList ++ Option(interfaces).toList.flatMap(_.toList)
        }

        override def visitOuterClass(owner: String, name: String, descriptor: String): Unit =
          outer = Some((owner, Option(name)))

        override def visitMethod(
          access: Int,
          name: String,
          descriptor: String,
          signature: String,
          exceptions: Array[String],
        ): MethodVisitor =
          // A sealed class's companion is its `Mirror.Sum`, whose `ordinal` method compares with each child `object`,
          // which doesn't make them used
          if (name == "ordinal" && supertypes.contains("scala/deriving/Mirror$Sum")) null
          else methodVisitor(name, (access & Opcodes.ACC_STATIC) != 0)
      },
      ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES,
    )

    ClassInfo(cls, supertypes, references.toSet, outer)
  }

  private case class ClassFile(entry: Path, name: String, read: () => Array[Byte])

  // Jars with class files in the analyzed packages are opened with `use` so they stay open until those have been read
  private def classFiles(entry: Path, packageDirs: List[String], use: Using.Manager): List[ClassFile] =
    if (Files.isDirectory(entry))
      packageDirs.map(entry.resolve).filter(Files.isDirectory(_)).flatMap(dir =>
        Using.resource(Files.walk(dir))(_.iterator.asScala.filter(_.toString.endsWith(".class")).toList).map(p =>
          ClassFile(entry, entry.relativize(p).toString, () => Files.readAllBytes(p))
        )
      )
    else if (Files.isRegularFile(entry) && entry.toString.endsWith(".jar")) {
      // A jar that can't be read is skipped like a class file that can't, rather than failing the whole analysis
      def skip(e: Throwable): List[ClassFile] = {
        println(s"[find-unused] Failed to read $entry: ${e.getMessage}")
        Nil
      }
      Either.catchNonFatal(new ZipFile(entry.toFile)).fold(skip, zip =>
        Either.catchNonFatal(zip.entries.asScala.filter(e =>
          !e.isDirectory && e.getName.endsWith(".class") && packageDirs.exists(d => e.getName.startsWith(d ++ "/"))
        ).toList) match {
          case Right(entries) if entries.nonEmpty =>
            use(zip)
            entries.map(e => ClassFile(entry, e.getName, () => Using.resource(zip.getInputStream(e))(_.readAllBytes)))
          case Right(_) =>
            zip.close()
            Nil
          case Left(e) =>
            zip.close()
            skip(e)
        }
      )
    } else
      Nil

  private def readClassFile(file: ClassFile, packagePrefixes: List[String]): Option[ClassInfo] =
    // ASM throws on class files newer than it supports; skip those rather than failing the whole analysis
    Either.catchNonFatal(readClass(file.read(), packagePrefixes)).leftMap(e =>
      println(s"[find-unused] Failed to read bytecode of ${file.name} in ${file.entry}: ${e.getMessage}")
    ).toOption

  // At most 3 threads, and at most half of the processors, so the rest of the machine stays responsive while this runs
  // alongside the analysis's own thread
  // Going from 1 to 3 threads makes the scan ~30% faster, but more threads than that only save a few more milliseconds
  def defaultThreads: Int = math.max(1, math.min(3, Runtime.getRuntime.availableProcessors / 2))

  def references(packages: Seq[String], classpath: Seq[Path], threads: Int = defaultThreads): BytecodeReferences = {
    // A package nested in another analyzed package is already read with it
    val allPackageDirs = packages.map(_.replace('.', '/')).toList.distinct
    val packageDirs = allPackageDirs.filterNot(d => allPackageDirs.exists(o => o != d && d.startsWith(o ++ "/")))
    val packagePrefixes = packageDirs.map(_ ++ "/")

    // Reading and parsing the class files is almost all of the time this takes, so do it in parallel
    val classes = Using.Manager { use =>
      val files = classpath.toList.flatMap(classFiles(_, packageDirs, use))
      val pool = Executors.newFixedThreadPool(threads)
      try
        pool.invokeAll(files.map(f => (() => readClassFile(f, packagePrefixes)): Callable[Option[ClassInfo]]).asJava)
          .asScala.toList.flatMap(_.get)
      finally pool.shutdown()
    }.get

    BytecodeReferences(
      classes.flatMap(c => c.references.map((r, m) => (r.name, (r.owner, (c.name, m))))).groupMap(_._1)(_._2)
        .view.mapValues(_.toSet).toMap,
      classes.map(c => c.name -> c.supertypes).toMap,
      classes.flatMap(c => c.outer.map(c.name -> _)).toMap,
    )
  }
}
